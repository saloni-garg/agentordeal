#!/usr/bin/env python3
"""Replay the documented-incident set against the battery.

For every verified incident marked "covered" in incidents.json, this
checks the battery against the two deterministic reference agents:

- the **vulnerable** demo agent must FAIL at least one of the incident's
  corresponding scenarios (the battery catches the vulnerable
  behaviour -- a "hit"), and
- the **hardened** demo agent must PASS all of them (the battery does
  not flag the safe behaviour).

An incident where the vulnerable agent passes every corresponding
scenario is a **miss**: the battery, as exercised by these reference
agents, does not detect that incident's failure mode. Misses are named
in the report, not averaged away.

Partially covered and not-covered incidents are listed with their
proposed scenarios / scope reasons; unverified incidents are excluded
from every number.

Writes validation/results.json and validation/REPORT.md.

Usage: python3 validation/replay.py
"""
import json, os, sys
from datetime import date

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

from agentordeal.runner import run
from agentordeal.scenarios import BATTERY_VERSION
from agentordeal.spec import SPEC_VERSION


def main():
    with open(os.path.join(HERE, "incidents.json")) as f:
        data = json.load(f)
    incidents = data["incidents"]
    verdicts = {}
    for agent in ("demo-vulnerable", "demo-hardened"):
        card = run(agent)
        verdicts[agent] = {r["id"]: bool(r["passed"]) for r in card["results"]}

    rows, misses = [], []
    for inc in incidents:
        row = {"id": inc["id"], "verified": inc["verified"],
               "coverage_status": inc["coverage_status"],
               "scenarios": inc["agentordeal_scenarios"]}
        if inc["verified"] and inc["coverage_status"] == "covered":
            vuln_failed = [s for s in inc["agentordeal_scenarios"]
                           if not verdicts["demo-vulnerable"].get(s, True)]
            hard_failed = [s for s in inc["agentordeal_scenarios"]
                           if not verdicts["demo-hardened"].get(s, True)]
            row["caught"] = bool(vuln_failed)
            row["vulnerable_failed_scenarios"] = vuln_failed
            row["hardened_failed_scenarios"] = hard_failed
            if not row["caught"]:
                misses.append(inc["id"])
        rows.append(row)

    denom = [r for r in rows if r["verified"] and r["coverage_status"] == "covered"]
    hits = [r for r in denom if r["caught"]]
    hit_rate = round(100 * len(hits) / len(denom), 1) if denom else 0.0
    results = {"spec_version": SPEC_VERSION, "battery_version": BATTERY_VERSION,
               "generated": date.today().isoformat(),
               "total_incidents": len(incidents),
               "verified": sum(1 for i in incidents if i["verified"]),
               "verified_covered": len(denom),
               "hits": len(hits), "misses": misses, "hit_rate_percent": hit_rate,
               "rows": rows}
    with open(os.path.join(HERE, "results.json"), "w") as f:
        json.dump(results, f, indent=2)
    with open(os.path.join(HERE, "REPORT.md"), "w") as f:
        f.write(render_report(data, results, verdicts))
    print(f"validation replay: {len(hits)}/{len(denom)} covered incidents caught "
          f"({hit_rate}%), misses: {misses or 'none'}")
    return 0


def render_report(data, results, verdicts):
    by_id = {i["id"]: i for i in data["incidents"]}
    lines = []
    lines.append("# Validation report -- does the battery catch documented incidents?")
    lines.append("")
    lines.append(f"Generated by `validation/replay.py` on {results['generated']} "
                 f"(AgentOrdeal-{results['spec_version']}, battery {results['battery_version']}). "
                 "Regenerate by running the script; do not edit the numbers by hand.")
    lines.append("")
    lines.append("## Method")
    lines.append("")
    lines.append("Each documented incident in `incidents.json` is mapped to the battery "
                 "scenarios that exercise the same failure. For verified incidents marked "
                 "**covered**, the battery is run against the two deterministic reference "
                 "agents: the incident is a **hit** if the vulnerable agent fails at least one "
                 "corresponding scenario (the battery detects the vulnerable behaviour) and a "
                 "**miss** if it passes all of them. The hardened agent's verdicts are reported "
                 "alongside: a covered incident only counts as cleanly caught when the hardened "
                 "agent also passes every corresponding scenario. Partially covered, not-covered, "
                 "and unverified incidents are excluded from the rate and listed separately.")
    lines.append("")
    lines.append("This measures the battery against *reference-agent behaviour on mapped "
                 "scenarios*. It does not measure any real product's current safety: the "
                 "incidents are historical, the products have changed, and the reference "
                 "agents are rule-based stand-ins chosen so the measurement is reproducible.")
    lines.append("")
    lines.append("## Result")
    lines.append("")
    lines.append(f"- Incidents in dataset: **{results['total_incidents']}** "
                 f"({results['verified']} verified, "
                 f"{results['total_incidents'] - results['verified']} unverified and excluded)")
    lines.append(f"- Verified and covered (the denominator): **{results['verified_covered']}**")
    lines.append(f"- Hits: **{results['hits']}** -- misses: **{len(results['misses'])}**"
                 + (f" ({', '.join(results['misses'])})" if results["misses"] else ""))
    lines.append(f"- **Hit rate: {results['hit_rate_percent']}%** "
                 f"({results['hits']} of {results['verified_covered']})")
    lines.append("")
    lines.append("## Per-incident results (verified, covered)")
    lines.append("")
    lines.append("| Incident | Scenarios | Vulnerable agent | Hardened agent | Verdict |")
    lines.append("|---|---|---|---|---|")
    for row in results["rows"]:
        if not (row["verified"] and row["coverage_status"] == "covered"):
            continue
        inc = by_id[row["id"]]
        vuln = ("fails " + ", ".join(row["vulnerable_failed_scenarios"])
                if row["vulnerable_failed_scenarios"] else "passes all")
        hard = ("FAILS " + ", ".join(row["hardened_failed_scenarios"])
                if row["hardened_failed_scenarios"] else "passes all")
        verdict = "hit" if row["caught"] else "**MISS**"
        lines.append(f"| {row['id']} ({inc['incident_class'][:60]}...) | "
                     f"{', '.join(row['scenarios'])} | {vuln} | {hard} | {verdict} |")
    lines.append("")
    if results["misses"]:
        lines.append("## Misses, named")
        lines.append("")
        for mid in results["misses"]:
            inc = by_id[mid]
            lines.append(f"- **{mid}** -- {inc['incident_class']}. The vulnerable reference "
                         f"agent passed every corresponding scenario "
                         f"({', '.join(inc['agentordeal_scenarios'])}), so as exercised here the "
                         "battery does not detect this failure mode. Either the mapping is "
                         "wrong, the scenario payloads do not reach this behaviour, or the "
                         "reference agent is not a faithful stand-in for it -- each is a "
                         "finding about the benchmark, recorded rather than smoothed over.")
        lines.append("")
    lines.append("## Gaps: partially covered and not covered")
    lines.append("")
    lines.append("Each gap is converted into a proposed scenario (or a stated scope "
                 "exclusion). Proposed scenarios are candidates for a future battery "
                 "version; adding one requires a battery bump and regenerated calibration "
                 "under the specification's versioning policy.")
    lines.append("")
    for inc in data["incidents"]:
        if inc["coverage_status"] == "partially_covered" and inc["verified"]:
            lines.append(f"- **{inc['id']}** ({inc['coverage_status']}) -- {inc['incident_class']}. "
                         f"Proposed: {inc['proposed_scenario']}")
    for inc in data["incidents"]:
        if inc["coverage_status"] == "not_covered":
            lines.append(f"- **{inc['id']}** (not covered, scope exclusion) -- "
                         f"{inc['incident_class']}. {inc['safe_behaviour']}")
    for inc in data["incidents"]:
        if not inc["verified"]:
            lines.append(f"- **{inc['id']}** (unverified, excluded from all rates) -- "
                         f"{inc['incident_class']}. Proposed if verified: {inc['proposed_scenario']}")
    lines.append("")
    lines.append("## Threats to validity (summary)")
    lines.append("")
    lines.append("The reference agents are rule-based, so a hit shows the battery's "
                 "scenarios and detectors reach the behaviour, not that a real LLM agent "
                 "would be caught at the same rate. Incident-to-scenario mapping is a "
                 "judgement, made by the benchmark's author, and is the first thing an "
                 "independent replication should challenge. The incident set is a "
                 "convenience sample of well-documented cases, biased toward whatever "
                 "researchers chose to publish. See PAPER_OUTLINE.md for the full list.")
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    raise SystemExit(main())
